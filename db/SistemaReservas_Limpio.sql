CREATE TABLE USUARIOS (
    ID VARCHAR2(50) PRIMARY KEY,
    CLAVE VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(30) NOT NULL
);

CREATE TABLE FUNCIONARIOS (
    ID VARCHAR2(50) PRIMARY KEY,
    NOMBRE VARCHAR2(150) NOT NULL,
    TELEFONO VARCHAR2(30),
    CONSTRAINT FK_FUNCIONARIO_USUARIO FOREIGN KEY (ID) REFERENCES USUARIOS(ID)
);

CREATE TABLE CATEGORIAS (
    ID VARCHAR2(50) PRIMARY KEY,
    DESCRIPCION VARCHAR2(200) NOT NULL
);

CREATE TABLE RECURSOS (
    ID VARCHAR2(50) PRIMARY KEY,
    CATEGORIA_ID VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,
    CONSTRAINT FK_RECURSO_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID)
);

CREATE TABLE RESERVAS (
    ID VARCHAR2(50) PRIMARY KEY,
    ACTIVIDAD VARCHAR2(200) NOT NULL,
    FECHA DATE NOT NULL,
    HORA_INICIO VARCHAR2(8) NOT NULL,
    HORA_FIN VARCHAR2(8) NOT NULL,
    FUNCIONARIO_ID VARCHAR2(50) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT CK_ESTADO_RESERVA CHECK (ESTADO IN ('ACTIVA', 'CANCELADA')),
    CONSTRAINT FK_RESERVA_FUNCIONARIO FOREIGN KEY (FUNCIONARIO_ID) REFERENCES FUNCIONARIOS(ID)
);

CREATE TABLE RESERVA_RECURSOS (
    RESERVA_ID VARCHAR2(50) NOT NULL,
    RECURSO_ID VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_RESERVA_RECURSOS PRIMARY KEY (RESERVA_ID, RECURSO_ID),
    CONSTRAINT FK_RR_RESERVA FOREIGN KEY (RESERVA_ID) REFERENCES RESERVAS(ID),
    CONSTRAINT FK_RR_RECURSO FOREIGN KEY (RECURSO_ID) REFERENCES RECURSOS(ID)
);

